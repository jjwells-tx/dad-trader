#!/bin/bash
# Non-interactive update, run on the server by GitHub Actions (.github/workflows/deploy.yml):
#
#   bash ~/releases/<sha>/deploy/update.sh <sha>
#
# 1. installs dependencies and runs the tests against the new code (stops here if they fail)
# 2. snapshots the running code, copies the new code into /opt/dad-trader (data/, out/ and .venv are left alone)
# 3. restarts the chat backend, republishes the rung sheet, and checks both
# 4. if step 3 fails, restores the snapshot so the old version keeps running
#
# First-time setup (packages, passwords, keys, cron, web server, systemd) is deploy/install.sh. Re-run that
# by hand when those pieces change; this script only updates the app code.
#
# Roll back by hand: bash ~/releases/<older sha>/deploy/update.sh <older sha>   (see: ls -t ~/releases)
set -euo pipefail

SHA="${1:-manual}"
APP=/opt/dad-trader
SRC="$(cd "$(dirname "$0")/.." && pwd)"
RELEASES="$HOME/releases"
SNAPSHOT="$RELEASES/previous.tar"
KEEP=5
say() { printf '\n==> %s\n' "$*"; }

if [[ ! -x "$APP/publish.sh" || ! -d "$APP/.venv" ]]; then
  echo "First-time setup hasn't been done on this server. Run deploy/install.sh once by hand (see README)."
  exit 1
fi
source "$APP/.venv/bin/activate"

say "Deploying ${SHA:0:7}"
say "Installing dependencies"
pip install -q -r "$SRC/requirements.txt" yfinance google-auth requests

say "Running tests against the new code"
( cd "$SRC" && python -m pytest -q -p no:cacheprovider )

say "Snapshotting the running version"
mkdir -p "$RELEASES"
tar -C "$APP" --exclude=./.venv --exclude=./data --exclude=./out -cf "$SNAPSHOT" .
PREV="$(cat "$APP/RELEASE" 2>/dev/null || echo unknown)"

rollback() {
  echo "!! Deploy failed; restoring the previous version ($PREV)"
  tar -C "$APP" -xf "$SNAPSHOT"
  if systemctl cat dad-trader-chat >/dev/null 2>&1; then sudo systemctl restart dad-trader-chat || true; fi
  "$APP/publish.sh" || true
  exit 1
}
trap rollback ERR

say "Installing the new code into $APP"
# publish.sh is generated by install.sh with this server's settings, so keep the server's copy
tar -C "$SRC" --exclude=./.venv --exclude=./data --exclude=./out --exclude=./.git --exclude='./*.json' \
    --exclude=./publish.sh -cf - . | tar -C "$APP" -xf -
echo "$SHA $(date '+%F %H:%M')" > "$APP/RELEASE"

if systemctl cat dad-trader-chat >/dev/null 2>&1; then
  say "Restarting the chat backend"
  sudo systemctl restart dad-trader-chat
  ok=""
  for _ in $(seq 1 15); do
    if curl -fsS --max-time 2 http://127.0.0.1:8001/healthz >/dev/null 2>&1; then ok=1; break; fi
    sleep 1
  done
  if [[ -z "$ok" ]]; then
    echo "Chat backend didn't come up:"; sudo journalctl -u dad-trader-chat -n 20 --no-pager || true
    rollback
  fi
else
  echo "WARN: dad-trader-chat service isn't installed yet. Re-run deploy/install.sh once to set up the AI chat."
fi

say "Republishing the rung sheet"
"$APP/publish.sh"

trap - ERR
say "Cleaning up old releases (keeping $KEEP)"
ls -1dt "$RELEASES"/*/ 2>/dev/null | tail -n +$((KEEP + 1)) | xargs -r rm -rf

say "Deployed ${SHA:0:7} (was ${PREV%% *})"
